const meaningByHanzi = new Map(Object.entries(HSK1_MEANINGS))

if (meaningByHanzi.size !== HSK1_VARIANT_CHARACTERS.length) {
  throw new Error('HSK 1 meanings must cover each selected Hanzi exactly once')
}
for (const hanzi of HSK1_VARIANT_CHARACTERS) {
  if (!meaningByHanzi.has(hanzi)) {
    throw new Error(`Missing HSK 1 meaning for ${hanzi}`)
  }
}

export function requireHsk1Meaning(hanzi: string): Hsk1Meaning {
  const meaning = meaningByHanzi.get(hanzi)
  if (!meaning) throw new Error(`Missing HSK 1 meaning for ${hanzi}`)
  return meaning
}

export function withHsk1Meanings(structure: CharacterStructure): CharacterStructure {
  const meaning = requireHsk1Meaning(structure.hanzi)
  return {
    ...structure,
    keyword: meaning.keyword,
    primitive: meaning.primitive,
    components: structure.components.map((component) => {
      const override = meaningByHanzi.get(component.hanzi)
      return override ? { ...component, keyword: override.keyword } : component
    }),
  }
}
